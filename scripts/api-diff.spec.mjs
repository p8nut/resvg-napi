import test from 'node:test';
import assert from 'node:assert/strict';
import { apiDiff, declarations, summary } from './api-diff.mjs';

// The shape napi writes: doc comments, one member per line.
const BASE = `/* auto-generated by NAPI-RS */
/* eslint-disable */

/** Read-only handle on a \`toy::Counter\`. */
export declare class Counter {
  label(): string
  /** How far one tick moves it. */
  step(by?: number | undefined | null): number
  get origin(): Point
  static fromLabel(label: string): Counter
  constructor(options: Options)
  get [globalThis.Symbol.toStringTag](): string
}

/** A new \`Counter\`. */
export declare function counter(options?: Options | undefined | null): Counter

export declare const enum Direction {
  Up = 'up',
  Down = 'down',
}

export interface Options {
  label?: string
  step?: number
}

export interface Point {
  x: number
  y: number
}

export type Kind = 'a' | 'b'

export declare namespace usvg {
  export declare function parse(svg: string): Point
}
`;

const edit = (from, to) => {
  assert.ok(BASE.includes(from), `fixture has ${from}`);
  return BASE.replace(from, to);
};

test('keys: container, member, accessor, static, constructor, namespace', () => {
  const keys = [...declarations(BASE).keys()];
  for (const k of [
    'Counter',
    'Counter.label',
    'Counter.get origin',
    'Counter.static fromLabel',
    'Counter.constructor',
    'Counter.get [globalThis.Symbol.toStringTag]',
    'counter',
    'Direction',
    'Direction.Up',
    'Options.label',
    'Kind',
    'usvg',
    'usvg.parse',
  ]) {
    assert.ok(keys.includes(k), `missing ${k} in ${keys.join(', ')}`);
  }
  assert.equal(declarations(BASE).get('Options.label'), '?: string');
});

test('no change', () => {
  const d = apiDiff(BASE, BASE);
  assert.equal(d.classification, 'none');
  assert.match(summary(d), /no change to the public API/i);
});

test('doc comments and whitespace only: none', () => {
  const head = BASE.replace(/\/\*\*[^]*?\*\//g, '/** Rewritten,\n * over two lines. */')
    .replace('label(): string', 'label():   string')
    .replace('x: number', '  x:number');
  assert.equal(apiDiff(BASE, head).classification, 'none');
});

test('a comment marker inside a string literal is not a comment', () => {
  const head = edit("Up = 'up'", "Up = 'up/*'");
  assert.equal(apiDiff(BASE, head).classification, 'breaking');
});

test('added class: additive, listed once', () => {
  const head = BASE + '\nexport declare class Extra {\n  a(): void\n  b(): void\n}\n';
  const d = apiDiff(BASE, head);
  assert.equal(d.classification, 'additive');
  assert.deepEqual(d.added, ['Extra', 'Extra.a', 'Extra.b']);
  const s = summary(d);
  assert.match(s, /\*\*Added\*\* \(1\)/);
  assert.doesNotMatch(s, /Extra\.a/);
});

test('added member, enum member, optional field, trailing optional param: additive', () => {
  for (const head of [
    edit('  label(): string\n', '  label(): string\n  reset(): void\n'),
    edit("  Down = 'down',\n", "  Down = 'down',\n  Sideways = 'sideways',\n"),
    edit('  step?: number\n', '  step?: number\n  wrap?: boolean\n'),
    edit('step(by?: number | undefined | null): number', 'step(by?: number | undefined | null, times?: number): number'),
    edit("export type Kind = 'a' | 'b'", "export type Kind = 'a' | 'b' | 'c'"),
  ]) {
    assert.equal(apiDiff(BASE, head).classification, 'additive', head);
  }
});

test('an interface merged into a class: additive', () => {
  const head = BASE + '\nexport interface Counter {\n  [Symbol.dispose](): void\n}\n';
  const d = apiDiff(BASE, head);
  assert.equal(d.classification, 'additive');
  assert.deepEqual(d.added, ['Counter.[Symbol.dispose]']);
  assert.match(d.changed[0].widening, /declaration merged: interface/);
  // ...but a class turned into an interface is not.
  assert.equal(apiDiff(BASE, edit('export declare class Counter', 'export interface Counter')).classification, 'breaking');
});

test('removed member: breaking', () => {
  const d = apiDiff(BASE, edit('  label(): string\n', ''));
  assert.equal(d.classification, 'breaking');
  assert.deepEqual(d.removed, ['Counter.label']);
  assert.match(summary(d), /\*\*Removed\*\* \(1\)\n\n- `Counter\.label`/);
});

test('changed parameter type: breaking', () => {
  const d = apiDiff(BASE, edit('fromLabel(label: string)', 'fromLabel(label: number)'));
  assert.equal(d.classification, 'breaking');
  assert.equal(d.changed[0].key, 'Counter.static fromLabel');
});

test('optional to required: breaking, for a parameter and for a field', () => {
  assert.equal(
    apiDiff(BASE, edit('counter(options?: Options', 'counter(options: Options')).classification,
    'breaking',
  );
  assert.equal(apiDiff(BASE, edit('  step?: number\n', '  step: number\n')).classification, 'breaking');
});

test('a new required field or parameter: breaking', () => {
  assert.equal(apiDiff(BASE, edit('  y: number\n', '  y: number\n  z: number\n')).classification, 'breaking');
  assert.equal(
    apiDiff(BASE, edit('fromLabel(label: string)', 'fromLabel(label: string, n: number)')).classification,
    'breaking',
  );
});

test('removed enum member and removed union member: breaking', () => {
  assert.equal(apiDiff(BASE, edit("  Down = 'down',\n", '')).classification, 'breaking');
  const d = apiDiff(BASE, edit("export type Kind = 'a' | 'b'", "export type Kind = 'a'"));
  assert.equal(d.classification, 'breaking');
  assert.equal(d.changed[0].key, 'Kind');
});

test('narrowed type: breaking', () => {
  const head = edit('step(by?: number | undefined | null)', 'step(by?: number)');
  assert.equal(apiDiff(BASE, head).classification, 'breaking');
});

test('a member moved into a namespace: breaking', () => {
  const head = edit('export declare function counter(', 'export declare namespace toy {\n  export function counter(')
    .replace('Counter\n\nexport declare const enum', 'Counter\n}\n\nexport declare const enum');
  const d = apiDiff(BASE, head);
  assert.equal(d.classification, 'breaking');
  assert.deepEqual(d.removed, ['counter']);
  assert.ok(d.added.includes('toy.counter'));
});

test('getter to method, static to instance: breaking', () => {
  assert.equal(apiDiff(BASE, edit('get origin(): Point', 'origin(): Point')).classification, 'breaking');
  assert.equal(apiDiff(BASE, edit('static fromLabel', 'fromLabel')).classification, 'breaking');
});

test('summary keeps PR text inside code spans', () => {
  const head = edit("Up = 'up'", "Up = '@someone `x` [link](http://e)'");
  const s = summary(apiDiff(BASE, head));
  for (const line of s.split('\n').filter((l) => l.includes('someone'))) {
    // Every backtick pairs up, and the injected one became a quote.
    assert.equal((line.match(/`/g) ?? []).length % 2, 0, line);
    assert.match(line, /`[^`]*@someone[^`]*`/);
  }
});
